/** 生成一层星点的 box-shadow 声明（1×1 透明元素铺星点） */
export function starShadows(points: readonly StarPoint[], rgb: string): string {
  return points.map(([x, y, a]) => x + 'px ' + y + 'px rgba(' + rgb + ', ' + a + ')').join(', ');
}
